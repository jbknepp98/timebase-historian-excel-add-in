// Generate docs/user-guide.md from the same content as the guide workbook.
//
//   node tools/make-docs.js          write docs/user-guide.md
//   node tools/make-docs.js --check  exit 1 if it is out of date
//
// One source (src/lib/guide-content.js) for both, so the Markdown guide and
// the Excel guide cannot disagree. test/guide.test.js runs the --check.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { GUIDE_SHEETS, GUIDE_VERSION } from "../src/lib/guide-content.js";

const ROOT = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
export const USER_GUIDE = path.join(ROOT, "docs", "user-guide.md");

const anchor = (name) =>
  name
    .toLowerCase()
    .replace(/[^a-z0-9 -]/g, "")
    .trim()
    .replace(/ /g, "-");

const cellText = (s) => String(s).replace(/\|/g, "\\|").replace(/\n/g, " ");

function table(header, rows, links) {
  const out = [`| ${header.map(cellText).join(" | ")} |`, `|${header.map(() => "---").join("|")}|`];
  for (const r of rows) {
    const cells = r.map((c, i) => (i === links ? `[${cellText(c)}](#${anchor(c)})` : cellText(c)));
    out.push(`| ${cells.join(" | ")} |`);
  }
  return out.join("\n");
}

/** Code-format the parts of plain text that are formulas or literal values. */
function renderSheet(sheet) {
  const lines = [];
  // Each sheet is a section; its own title becomes the heading.
  for (const b of sheet.blocks) {
    if (b.title) lines.push(`## ${sheet.name === b.title ? b.title : sheet.name}`, "");
    else if (b.subtitle) lines.push(`*${b.subtitle}*`, "");
    else if (b.heading) lines.push(`### ${b.heading}`, "");
    else if (b.text) lines.push(b.text, "");
    else if (b.bullets) {
      for (const t of b.bullets) lines.push(/^\d+\./.test(t) ? t : `- ${t}`);
      lines.push("");
    } else if (b.table) lines.push(table(b.table.header, b.table.rows, b.table.links), "");
    else if (b.input) {
      const { label, name, values, note } = b.input;
      const shown = values.map((v) => `\`${v}\``).join(", ");
      lines.push(`- **${label}**${name ? ` (named \`${name}\`)` : ""}: ${shown}${note ? ` -- ${note}` : ""}`, "");
    } else if (b.example) {
      lines.push(`**${b.example.label}**`, "", "```", b.example.formula, "```", "");
    }
  }
  return lines.join("\n");
}

export function renderUserGuide() {
  const toc = GUIDE_SHEETS.map((s) => `- [${s.name}](#${anchor(s.name)})`).join("\n");
  const body = GUIDE_SHEETS.map(renderSheet).join("\n");
  return (
    `# User guide\n\n` +
    `<!-- GENERATED by tools/make-docs.js from src/lib/guide-content.js -- edit that file, then run node tools/make-docs.js -->\n\n` +
    `The same content as the getting-started workbook (guide version ${GUIDE_VERSION}): open ` +
    "`Timebase Historian Guide.xlsx`, or add it to any workbook from the task pane's " +
    "**Connect** tab, **Getting started** section, to run every example live. The formulas below use the " +
    "workbook's named Setup cells (`Guide_Dataset`, `Guide_StateTags`, ...); in your own sheets, put " +
    "the dataset and tag names in their place.\n\n" +
    `${toc}\n\n${body}`.replace(/\n{3,}/g, "\n\n")
  );
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const md = renderUserGuide();
  if (process.argv.includes("--check")) {
    const current = fs.existsSync(USER_GUIDE) ? fs.readFileSync(USER_GUIDE, "utf8") : "";
    if (current !== md) {
      console.error("docs/user-guide.md is out of date. Run: node tools/make-docs.js");
      process.exit(1);
    }
    console.log("docs/user-guide.md is up to date.");
  } else {
    fs.writeFileSync(USER_GUIDE, md);
    console.log(`Wrote ${path.relative(process.cwd(), USER_GUIDE)}`);
  }
}
