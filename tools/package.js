// Produce a deployable bundle for a specific host.
//
//   node tools/package.js https://historian.example.com:4512
//
// An Office add-in has no single-file package (no .mez equivalent). It has two
// deliverables that go to different places, so that is what this emits:
//
//   dist/web/           -> unpack at your web root; these are the hosted assets
//   dist/manifest.xml   -> sideload this into Excel, or push it via M365 admin
//
// The whole job here is substituting the host into manifest.xml without
// missing one of the places it appears, and then proving none were missed.

import fs from "node:fs";
import path from "node:path";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import { bundle } from "./bundle.js";

const ROOT = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const DIST = path.join(ROOT, "dist");
const WEB = path.join(DIST, "web");

const PLACEHOLDER = "https://REPLACE_WITH_YOUR_HOST";

// --- validate the host ---------------------------------------------------------

const args = process.argv.slice(2);
// No ribbon by default. Since the 24-25 Sept 2026 Office update, a SIDELOADED
// add-in that declares add-in commands (the Home-tab button) is not listed in
// Home > Add-ins and fails to activate from a workbook ("This add-in is no
// longer available", HRESULT 0x80043251; OfficeDev/office-js#6973). Confirmed
// on Excel for Mac 16.105: without the commands the same add-in loads -- task
// pane and TB.* functions -- and starts from any workbook saved with it (see
// "the launcher workbook" below). Pass --ribbon to put the button back once
// Microsoft fixes the regression.
const noRibbon = !args.includes("--ribbon");
const raw = args.find((a) => !a.startsWith("--"));
if (!raw) {
  console.error(
    [
      "Usage: node tools/package.js <host-url>",
      "",
      "The host URL is where you will serve this add-in's files from. Examples:",
      "",
      "  node tools/package.js https://historian.example.com:4512",
      "  node tools/package.js https://localhost:3443        (local sideload testing)",
      "",
      "Hosting on the Historian itself is recommended: it makes every API call",
      "same-origin, so CORS never enters the picture.",
    ].join("\n"),
  );
  process.exit(1);
}

let host;
try {
  const u = new URL(raw);
  if (u.protocol !== "https:") {
    // Office refuses to load an add-in over plain HTTP, including on localhost.
    // Failing here beats a silent blank task pane later.
    console.error(`Office add-ins must be served over HTTPS. Got: ${u.protocol}//`);
    process.exit(1);
  }
  // Normalise away any path/trailing slash: the manifest appends its own paths.
  host = `${u.protocol}//${u.host}`;
} catch {
  console.error(`Not a valid URL: ${raw}`);
  process.exit(1);
}

// --- copy the web assets --------------------------------------------------------

fs.rmSync(DIST, { recursive: true, force: true });
fs.mkdirSync(WEB, { recursive: true });

for (const dir of ["src", "assets"]) {
  fs.cpSync(path.join(ROOT, dir), path.join(WEB, dir), { recursive: true });
}

// The custom-functions script, flattened to one classic script (see
// tools/bundle.js for why Excel for Mac needs that).
fs.writeFileSync(
  path.join(WEB, "src", "functions", "functions.bundle.js"),
  bundle(path.join(ROOT, "src", "functions", "functions.js")),
);

// --- substitute the host into the manifest ---------------------------------------

const manifestSrc = fs.readFileSync(path.join(ROOT, "manifest.xml"), "utf8");
const occurrences = manifestSrc.split(PLACEHOLDER).length - 1;

// Drop the source manifest's "replace this placeholder" instruction from the
// built copy. Left in, it would substitute into nonsense ("every
// https://your-real-host value must be changed to...") and read as a step the
// deployer still has to perform, when it has already been done for them.
const withoutInstruction = manifestSrc.replace(
  /\n\n  Placeholder: every[\s\S]*?hosting choices\./,
  `\n\n  GENERATED by tools/package.js for ${host}. Do not hand-edit: re-run the\n  packager against a different host instead, so no URL is missed.`,
);

let manifestOut = withoutInstruction.split(PLACEHOLDER).join(host);
if (noRibbon) {
  const before = manifestOut;
  // The whole DesktopFormFactor goes: the schema requires it to hold at least
  // one ExtensionPoint, and every desktop extension point is an add-in command.
  manifestOut = manifestOut
    .replace(/\n\s*<DesktopFormFactor>[\s\S]*?<\/DesktopFormFactor>\n/, "\n")
    .replace(/<OfficeApp/, "<!-- Built without the Home-tab button (the default). See tools/package.js. -->\n<OfficeApp");
  if (manifestOut === before || /<DesktopFormFactor>/.test(manifestOut)) {
    console.error("Could not remove the DesktopFormFactor block for the no-ribbon build.");
    process.exit(1);
  }
}

// Prove the substitution was complete. A single missed placeholder means Excel
// silently fails to load one resource -- an icon, or worse, functions.json --
// with no useful error, so this is asserted rather than assumed.
const leftover = manifestOut.match(/REPLACE_WITH_YOUR_HOST/g);
if (leftover) {
  console.error(`Substitution incomplete: ${leftover.length} placeholder(s) remain.`);
  process.exit(1);
}

fs.writeFileSync(path.join(DIST, "manifest.xml"), manifestOut);

// --- the launcher workbook ----------------------------------------------------------
//
// A one-sheet workbook whose only content is a reference to this add-in (by id
// and exact version) with its task pane set to open. Opening it is how the
// add-in starts while the ribbon is unavailable (the default build), and a workbook
// saved from it keeps the reference. The version must match the manifest
// exactly: a stale version reads as "This add-in is no longer available".

const addinId = (manifestOut.match(/<Id>([^<]+)<\/Id>/) || [])[1];
const addinVersion = (manifestOut.match(/<Version>([^<]+)<\/Version>/) || [])[1];
let launcherPath = path.join(DIST, "Timebase Historian.xlsx");
try {
  const staging = path.join(DIST, ".launcher");
  fs.cpSync(path.join(ROOT, "tools", "launcher-template"), staging, { recursive: true });
  const ext = path.join(staging, "xl", "webextensions", "webextension.xml");
  fs.writeFileSync(
    ext,
    fs.readFileSync(ext, "utf8").split("ADDIN_ID").join(addinId).split("ADDIN_VERSION").join(addinVersion),
  );
  // -X: no macOS extra attributes; -D: no directory entries. [Content_Types].xml
  // goes first, as OOXML readers expect.
  execFileSync("zip", ["-qXD", launcherPath, "[Content_Types].xml"], { cwd: staging });
  execFileSync("zip", ["-qXDr", launcherPath, "_rels", "xl"], { cwd: staging });
  fs.rmSync(staging, { recursive: true, force: true });
} catch {
  launcherPath = null;
}

// --- the getting-started guide ------------------------------------------------------
//
// guide/Timebase Historian Guide.xlsx is built once in Excel with the task
// pane's "Add the getting-started guide" button and saved with the task pane
// open, so it carries a reference to this add-in. That reference names an exact
// add-in version; it is re-stamped here with this build's id and version so the
// shipped guide keeps opening the add-in after a version bump.

const GUIDE_SRC = path.join(ROOT, "guide", "Timebase Historian Guide.xlsx");
let guidePath = null;
let guideNote = "guide/Timebase Historian Guide.xlsx not found; build it with the task pane's guide button";
if (fs.existsSync(GUIDE_SRC)) {
  try {
    const staging = path.join(DIST, ".guide");
    fs.mkdirSync(staging, { recursive: true });
    execFileSync("unzip", ["-q", GUIDE_SRC, "-d", staging]);
    const extDir = path.join(staging, "xl", "webextensions");
    let stamped = 0;
    for (const f of fs.existsSync(extDir) ? fs.readdirSync(extDir) : []) {
      if (!/^webextension\d*\.xml$/.test(f)) continue;
      const file = path.join(extDir, f);
      const xml = fs.readFileSync(file, "utf8");
      const out = xml.replace(/<we:reference\b[^>]*\/>/, (tag) => {
        stamped++;
        return tag.replace(/\bid="[^"]*"/, `id="${addinId}"`).replace(/\bversion="[^"]*"/, `version="${addinVersion}"`);
      });
      fs.writeFileSync(file, out);
    }
    guidePath = path.join(DIST, "Timebase Historian Guide.xlsx");
    const entries = fs.readdirSync(staging).filter((e) => e !== "[Content_Types].xml");
    execFileSync("zip", ["-qXD", guidePath, "[Content_Types].xml"], { cwd: staging });
    execFileSync("zip", ["-qXDr", guidePath, ...entries], { cwd: staging });
    fs.rmSync(staging, { recursive: true, force: true });
    guideNote = stamped
      ? `opens the add-in (reference stamped to v${addinVersion})`
      : "WARNING: no add-in reference inside; save the guide with the task pane open";
  } catch (err) {
    guidePath = null;
    guideNote = `could not package the guide: ${err.message}`;
  }
}

// --- zip the web bundle, if the platform has zip ----------------------------------

let zipPath = path.join(DIST, "timebase-historian-excel-web.zip");
try {
  // -r recurse, -q quiet, -X drop macOS resource forks that would otherwise
  // ride along and confuse a strict web server.
  execFileSync("zip", ["-rqX", zipPath, "src", "assets"], { cwd: WEB });
} catch {
  zipPath = null;
}

// --- report ------------------------------------------------------------------------

const rel = (p) => path.relative(ROOT, p);

console.log(`Host:        ${host}${noRibbon ? "   (no ribbon button; --ribbon to add it)" : "   (--ribbon)"}`);
console.log(`Substituted: ${occurrences} placeholder(s) in manifest.xml`);
console.log("");
console.log("Built:");
console.log(`  ${rel(path.join(DIST, "manifest.xml"))}   <- sideload this into Excel`);
console.log(`  ${rel(WEB)}/                 <- serve these files at ${host}`);
if (zipPath) console.log(`  ${rel(zipPath)}  <- same files, zipped for transfer`);
else console.log("  (zip unavailable on this system; copy dist/web/ as-is)");
if (launcherPath) console.log(`  ${rel(launcherPath)}    <- open this to start the add-in (id ${addinId}, v${addinVersion})`);
console.log(guidePath ? `  ${rel(guidePath)}  <- getting-started guide; ${guideNote}` : `  (guide: ${guideNote})`);
console.log("");
console.log("Verify the hosted layout resolves to these URLs:");
console.log(`  ${host}/src/taskpane/taskpane.html`);
console.log(`  ${host}/src/functions/functions.json`);
console.log(`  ${host}/assets/icon-32.png`);
console.log("");
console.log(
  "Then, in the task pane's Connect tab, enter this same host as the Historian (and,",
);
console.log(
  "behind a proxy that forwards /auth, Pulse) address. Same-origin needs no CORS, and",
);
console.log("the Historian and Pulse send no CORS headers, so a different origin is blocked.");
